#!/usr/bin/env python3
"""Render benchmark reports and images for the automated publication PR.

    python3 bench/publish.py bench/results/<timestamp>

Multiple bundle directories can be combined with --merge-dir. Historical result JSON is also supported.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
from statistics import mean

import chart
import results
import run

REPO = run.REPO
# The summary tables, all from the measure jobs: each compiler at its own default, then both at 1, 2, 4 (tsgo's
# default) and 8 checker threads, the chart's points. Modes a result lacks are skipped.
PUBLISHED_MODES = ["wide", *chart.POINTS.values()]


# bench/RESULTS.md's per-project charts, drawn beside the README chart: the file stem for each metric.
PER_PROJECT = {"wall_s": "per-project-time", "peak_rss_bytes": "per-project-memory"}
RAW = "https://raw.githubusercontent.com/oxc-project/tsrs/main/bench"


def dark_image(image_path: Path) -> Path:
    """The dark-theme chart that sits next to the light one, e.g. large-projects-dark.svg."""
    return image_path.with_name(f"{image_path.stem}-dark{image_path.suffix}")


def picture(stem: str, alt: str) -> str:
    """The light or dark chart to match the reader's GitHub theme, as README.md shows the summary chart."""
    return (f'<picture>\n  <source media="(prefers-color-scheme: dark)" srcset="{RAW}/{stem}-dark.svg">\n'
            f'  <img alt="{alt}" src="{RAW}/{stem}.svg">\n</picture>\n')


def publish(result_path: Path, report: Path, image_path: Path) -> bool:
    result = json.loads(result_path.read_text())
    # Both Bun comparison jobs must have finished: with one, the tables and chart would show half the projects.
    for mode in ("wide", chart.MODE):
        if mode not in result["modes"] or not all(mode in p for p in result["projects"].values()):
            print(f"No {mode} results for every project; keeping the latest report and chart.")
            return False

    measured = subprocess.check_output(
        ["git", "rev-parse", "--verify", f"{result['tsrs']['commit']}^{{commit}}"], cwd=REPO, text=True).strip()
    report_text = report.read_text()
    match = re.search(r"tsrs commit: `([0-9a-f]{7,40})`", report_text)
    if match:
        resolved = subprocess.run(["git", "rev-parse", "--verify", f"{match[1]}^{{commit}}"],
                                  cwd=REPO, capture_output=True, text=True)
        displayed = resolved.stdout.strip()
        if resolved.returncode == 0 and displayed != measured and subprocess.run(
                ["git", "merge-base", "--is-ancestor", measured, displayed], cwd=REPO).returncode == 0:
            print(f"Keeping the report and chart of {displayed[:12]}, a descendant of {measured[:12]}.")
            return False

    # Render everything before writing anything so a rendering failure cannot leave a mismatched set.
    svg = chart.svg(result, "light")
    dark_svg = chart.svg(result, "dark")
    details = {image_path.with_name(f"{stem}{suffix}.svg"): chart.per_project_svg(result, metric, theme)
               for metric, stem in PER_PROJECT.items() for theme, suffix in (("light", ""), ("dark", "-dark"))}
    table = run.markdown(result, PUBLISHED_MODES)
    notice = "<!-- Generated by bench/publish.py; edit the generator, not this section. -->\n\n"
    charts = "".join(picture(stem, f"{chart.DETAIL[metric][0]} by project") + "\n"
                     for metric, stem in PER_PROJECT.items())
    sources = f"\n[All modes](results/{result_path.stem}.md) · [Raw measurements](results/{result_path.name})\n"
    block = f"{run.START}\n{notice}{charts}{table}{sources}{run.END}"
    before, rest = report_text.split(run.START, 1)
    _, after = rest.split(run.END, 1)
    report.write_text(before + block + after)
    image_path.write_text(svg)
    dark_image(image_path).write_text(dark_svg)
    for path, image in details.items():
        path.write_text(image)
    print(f"Updated {report}, {image_path}, {dark_image(image_path)} and the per-project charts for {measured[:12]}.")
    return True


def publish_bundle(source: Path, destination: Path, commit: str | None, run_url: str | None) -> None:
    """Write publication files separately from the raw bundle, which stays in the CI artifact."""
    import chart_bars
    meta, rows, preflights = results.load_bundle(source)
    result = results.for_chart(source)
    destination.mkdir(parents=True, exist_ok=True)
    for theme, suffix in (("light", ""), ("dark", "-dark")):
        (destination / f"large-projects{suffix}.svg").write_text(chart.svg(result, theme))
        for metric, stem in PER_PROJECT.items():
            (destination / f"{stem}{suffix}.svg").write_text(chart.per_project_svg(result, metric, theme))
    chart_bars.render(source, source / 'charts')
    (destination / 'benchmark.svg').write_bytes((source / 'charts/benchmark.svg').read_bytes())
    settings = meta['settings']
    lines = ['# Benchmark results', '', run.START,
             '<!-- Generated by bench/publish.py; edit the generator, not this section. -->', '',
             f"Measured {meta['started_utc']} on {meta['machine']['label']}.", '',
             f"Arithmetic means of {meta['runs']} runs after {meta['warmup']} warmups per compiler/project. "
             'Peak memory is the mean process peak RSS. Projects are never averaged together.', '',
             f"{settings['checkers']} checkers and {settings['workers']} worker CPUs per compiler. "
             + (f"Soft memory budget: {settings['memory_gib']} GiB." if settings['memory_gib'] else 'Default memory policy.'), '',
             f"Shared flags: `-p <project> {' '.join(run.TIMED_FLAGS)} --checkers {settings['checkers']}`.", '']
    if commit:
        lines += [f"tsrs commit: `{commit}` (PGO + BOLT build).", '']
    if run_url:
        lines += [f'[Benchmark run and raw-data artifacts]({run_url}).', '']
    lines += ['[Methodology](README.md).', '', '![All measured compiler versions](benchmark.svg)', '']
    for metric, stem in PER_PROJECT.items():
        lines += [picture(stem, f'{chart.DETAIL[metric][0]} by project'), '']
    lines += ['| Project | Compiler | Wall time | Peak memory | Instructions | Files | Diagnostics |',
              '| --- | --- | ---: | ---: | ---: | ---: | ---: |']
    for project in meta['projects']:
        name = project['name']
        for compiler in ['tsrs', *[c for c in meta['compilers'] if c != 'tsrs']]:
            group = [r for r in rows if r['project'] == name and r['compiler'] == compiler]
            info, check = meta['compilers'][compiler], preflights[name]['compilers'][compiler]
            lines.append(f"| {name} | {info['label']} {info['version']} | "
                         f"{mean(r['wall_seconds'] for r in group):.3f} s | "
                         f"{mean(r['peak_rss_bytes'] for r in group) / 2**30:.3f} GiB | "
                         f"{mean(r['instructions'] for r in group):,.0f} | {check['files']} | {check['errors']} |")
    lines += ['', 'File counts and diagnostics are collected in separate, untimed runs.', '', run.END, '']
    (destination / 'RESULTS.md').write_text('\n'.join(lines))
    print(f'Publication report and images: {destination}')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("result", type=Path, nargs='+')
    parser.add_argument("--merge-dir", type=Path, help="combine project bundles into this new artifact directory")
    parser.add_argument("--output-dir", type=Path, default=run.BENCH, help="publication report and SVG destination")
    parser.add_argument("--commit", help="source commit of the CI-built PGO + BOLT tsrs binary")
    parser.add_argument("--run-url", help="workflow run containing the raw-data artifacts")
    args = parser.parse_args()
    if args.merge_dir:
        source = results.merge_bundles(args.result, args.merge_dir)
    elif len(args.result) == 1:
        source = args.result[0]
    else:
        parser.error('multiple result bundles require --merge-dir')
    if source.is_dir():
        publish_bundle(source, args.output_dir, args.commit, args.run_url)
    else:
        publish(source, args.output_dir / 'RESULTS.md', args.output_dir / 'large-projects.svg')


if __name__ == "__main__":
    main()
