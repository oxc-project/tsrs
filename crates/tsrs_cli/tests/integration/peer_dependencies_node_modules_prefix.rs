// Go `readPackageJsonPeerDependencies` splits the real path of a package at the last path component that is exactly
// `node_modules`. The Rust port searches for the text `/node_modules`, so a directory such as `node_modules_x` also
// matches. For a package whose real path is `store/node_modules_x/pkg`, tsrs looks for peers in `store/node_modules/`
// and adds `+peer@2.0.0` to the package ID. tsgo finds no `node_modules` component and adds nothing. The IDs of the two
// copies of `pkg@1.0.0` then differ in tsrs, so tsrs does not merge them and reports TS2322 for a private property.
// Expected values were taken from tsgo built from the pinned ts-ref commit: empty stdout and exit status 0. The case
// needs `node_modules` directories and a symbolic link, so it is created at run time (Unix only).

#![cfg(unix)]

use std::path::{Path, PathBuf};
use std::process::Command;

const PACKAGE_JSON: &str =
    r#"{"name":"pkg","version":"1.0.0","types":"index.d.ts","peerDependencies":{"peer":"*"}}"#;
const PACKAGE_DTS: &str = "export declare class C { private p; }\n";

fn scratch(name: &str, files: &[(&str, &str)]) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "tsrs-peer-dependencies-node-modules-prefix-{}-{}",
        name,
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&dir);
    for (path, text) in files {
        let file = dir.join(path);
        std::fs::create_dir_all(file.parent().unwrap()).unwrap();
        std::fs::write(file, text).unwrap();
    }
    dir
}

fn tsrs(args: &[&str], dir: &Path) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_tsrs"))
        .args(args)
        .args(["--pretty", "false", "--singleThreaded"])
        .current_dir(dir)
        .env_remove("TSRS_FAST")
        .output()
        .unwrap()
}

#[test]
fn duplicate_package_in_directory_that_starts_with_node_modules() {
    let dir = scratch(
        "dedup",
        &[
            (
                "tsconfig.json",
                r#"{"compilerOptions":{"module":"esnext","moduleResolution":"bundler","noEmit":true,"strict":true},"files":["index.ts"]}"#,
            ),
            (
                "index.ts",
                "import { a } from \"a\";\nimport { b } from \"b\";\nlet x = a;\nx = b;\n",
            ),
            (
                "node_modules/a/index.d.ts",
                "import { C } from \"pkg\";\nexport declare const a: C;\n",
            ),
            (
                "node_modules/b/index.d.ts",
                "import { C } from \"pkg\";\nexport declare const b: C;\n",
            ),
            ("store/node_modules_x/pkg/package.json", PACKAGE_JSON),
            ("store/node_modules_x/pkg/index.d.ts", PACKAGE_DTS),
            ("node_modules/b/node_modules/pkg/package.json", PACKAGE_JSON),
            ("node_modules/b/node_modules/pkg/index.d.ts", PACKAGE_DTS),
            ("store/node_modules/peer/package.json", r#"{"name":"peer","version":"2.0.0"}"#),
        ],
    );
    // `a` reaches `pkg` through a link into a store directory whose name starts with `node_modules`.
    let link = dir.join("node_modules/a/node_modules/pkg");
    std::fs::create_dir_all(link.parent().unwrap()).unwrap();
    std::os::unix::fs::symlink("../../../store/node_modules_x/pkg", &link).unwrap();
    let out = tsrs(&["-p", "."], &dir);
    assert_eq!(
        (out.status.code(), String::from_utf8_lossy(&out.stdout).as_ref()),
        (Some(0), ""),
        "stderr: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let _ = std::fs::remove_dir_all(&dir);
}
