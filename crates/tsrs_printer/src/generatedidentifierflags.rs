use bitflags::bitflags;

bitflags! {
    #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Debug, Default)]
    pub struct GeneratedIdentifierFlags: u32 {
        // Kind

        const NONE = 0; // Not automatically generated.
        const AUTO = 1; // Automatically generated identifier.
        const LOOP = 2; // Automatically generated identifier with a preference for '_i'.
        const UNIQUE = 3; // Unique name based on the 'text' property.
        const NODE = 4; // Unique name based on the node in the 'Node' property.
        const KIND_MASK = 7; // Mask to extract the kind of identifier from its flags.

        // Flags

        const RESERVED_IN_NESTED_SCOPES = 1 << 3; // Reserve the generated name in nested scopes
        const OPTIMISTIC = 1 << 4; // First instance won't use '_#' if there's no conflict
        const FILE_LEVEL = 1 << 5; // Use only the file identifiers list and not generated names to search for conflicts
        const ALLOW_NAME_SUBSTITUTION = 1 << 6; // Used by `module.ts` to indicate generated nodes which can have substitutions performed upon them (as they were generated by an earlier transform phase)
    }
}

impl GeneratedIdentifierFlags {
    #[must_use]
    pub fn kind(self) -> GeneratedIdentifierFlags {
        self & GeneratedIdentifierFlags::KIND_MASK
    }

    pub fn is_auto(self) -> bool {
        self.kind() == GeneratedIdentifierFlags::AUTO
    }

    pub fn is_loop(self) -> bool {
        self.kind() == GeneratedIdentifierFlags::LOOP
    }

    pub fn is_unique(self) -> bool {
        self.kind() == GeneratedIdentifierFlags::UNIQUE
    }

    pub fn is_node(self) -> bool {
        self.kind() == GeneratedIdentifierFlags::NODE
    }

    pub fn is_reserved_in_nested_scopes(self) -> bool {
        self.intersects(GeneratedIdentifierFlags::RESERVED_IN_NESTED_SCOPES)
    }

    pub fn is_optimistic(self) -> bool {
        self.intersects(GeneratedIdentifierFlags::OPTIMISTIC)
    }

    pub fn is_file_level(self) -> bool {
        self.intersects(GeneratedIdentifierFlags::FILE_LEVEL)
    }

    pub fn has_allow_name_substitution(self) -> bool {
        self.intersects(GeneratedIdentifierFlags::ALLOW_NAME_SUBSTITUTION)
    }
}
