// Generates crates/tsrs_core/src/stringutil/js_case_generated.rs (src/main.rs is its command line), a library so the
// integration tests can call it.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

pub mod source;

pub type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

const DESTINATION: &str = "crates/tsrs_core/src/stringutil/js_case_generated.rs";
const HEADER: &str = r"// Code generated by tasks/generate_stringutil. DO NOT EDIT.
// Source: @unicode/unicode-15.1.0@1.6.17 (Unicode 15.1.0).

use super::rangetable::{Range16, Range32, RangeTable};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum SpecialCasingCondition {
    None,
    FinalSigma,
}

#[derive(Clone, Copy, Debug)]
pub struct SpecialCasingMapping {
    lower_offset: u16,
    upper_offset: u16,
    conditional_lower_offset: u16,
    lower_length: u8,
    upper_length: u8,
    conditional_lower_length: u8,
    pub condition: SpecialCasingCondition,
}

const _: () = assert!(std::mem::size_of::<(u32, SpecialCasingMapping)>() == 16);

impl SpecialCasingMapping {
    pub fn lower(&self) -> &'static [u8] {
        Self::text(self.lower_offset, self.lower_length)
    }

    pub fn upper(&self) -> &'static [u8] {
        Self::text(self.upper_offset, self.upper_length)
    }

    pub fn conditional_lower(&self) -> &'static [u8] {
        Self::text(self.conditional_lower_offset, self.conditional_lower_length)
    }

    fn text(offset: u16, length: u8) -> &'static [u8] {
        let start = usize::from(offset);
        // The generator validates UTF-8 boundaries; runtime slicing checks byte bounds.
        &CASING_STRINGS.as_bytes()[start..start + usize::from(length)]
    }
}
";

pub fn run() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let check = match args.as_slice() {
        [] => false,
        [arg] if arg == "--write" => false,
        [arg] if arg == "--check" => true,
        [arg] if arg == "--help" || arg == "-h" => {
            println!("cargo run -p tsrs_generate_stringutil -- [--write|--check]");
            return Ok(());
        }
        _ => return Err("expected --write (default) or --check".into()),
    };
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().parent().unwrap();
    let generated = generate(&source::load(root)?)?;
    let mut rustfmt = Command::new("rustfmt")
        .current_dir(root)
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()?;
    rustfmt.stdin.take().unwrap().write_all(generated.as_bytes())?;
    let formatted = rustfmt.wait_with_output()?;
    if !formatted.status.success() {
        return Err(format!("rustfmt failed: {}", formatted.status).into());
    }
    let destination = root.join(DESTINATION);
    if check {
        if std::fs::read(&destination)? != formatted.stdout {
            return Err(
                "compact tables are stale; run cargo run -p tsrs_generate_stringutil".into()
            );
        }
        println!("{DESTINATION} is up to date");
    } else {
        std::fs::write(destination, formatted.stdout)?;
        println!("wrote {DESTINATION}");
    }
    Ok(())
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Slice {
    pub offset: u16,
    pub length: u8,
}

#[derive(Default)]
pub struct Pool {
    pub text: String,
    strings: BTreeMap<String, Slice>,
}

impl Pool {
    pub fn insert(&mut self, text: &str) -> Result<Slice> {
        if let Some(slice) = self.strings.get(text) {
            return Ok(*slice);
        }
        let offset = u16::try_from(self.text.len())?;
        let length = u8::try_from(text.len())?;
        if self.text.len() + text.len() > usize::from(u16::MAX) {
            return Err("string pool exceeds u16 offsets".into());
        }
        self.text.push_str(text);
        let slice = Slice { offset, length };
        self.strings.insert(text.to_owned(), slice);
        Ok(slice)
    }

    pub fn validate(&self) -> Result<()> {
        for (text, slice) in &self.strings {
            let start = usize::from(slice.offset);
            let end = start + usize::from(slice.length);
            if self.text.get(start..end) != Some(text.as_str()) {
                return Err("mapping did not round-trip through the UTF-8 pool".into());
            }
        }
        Ok(())
    }
}

fn generate(files: &BTreeMap<&str, String>) -> Result<String> {
    let simple_lower = source::mapping(&files["Simple_Case_Mapping/Lowercase/code-points.js"])?;
    let simple_upper = source::mapping(&files["Simple_Case_Mapping/Uppercase/code-points.js"])?;
    let special_lower = source::mapping(&files["Special_Casing/Lowercase/code-points.js"])?;
    let special_upper = source::mapping(&files["Special_Casing/Uppercase/code-points.js"])?;
    let final_sigma =
        source::mapping(&files["Special_Casing/Lowercase--Final_Sigma/code-points.js"])?;
    // Follow TypeScript's generate-unicode-data.mts: full, locale-insensitive
    // mappings override simple mappings; only Final_Sigma is contextual.
    let keys: BTreeSet<_> =
        [&simple_lower, &simple_upper, &special_lower, &special_upper, &final_sigma]
            .into_iter()
            .flat_map(|map| map.keys().copied())
            .collect();
    if keys.is_empty() {
        return Err("no casing mappings found".into());
    }
    let mut pool = Pool::default();
    let mut entries = String::new();
    for key in keys {
        let identity = source::scalar(key)?.to_string();
        let lower = pool.insert(
            special_lower.get(&key).or_else(|| simple_lower.get(&key)).unwrap_or(&identity),
        )?;
        let upper = pool.insert(
            special_upper.get(&key).or_else(|| simple_upper.get(&key)).unwrap_or(&identity),
        )?;
        let conditional = pool.insert(final_sigma.get(&key).map_or("", String::as_str))?;
        let condition = if final_sigma.contains_key(&key) { "FinalSigma" } else { "None" };
        writeln!(entries, "(0x{key:X}, SpecialCasingMapping {{ lower_offset: {}, upper_offset: {}, conditional_lower_offset: {}, lower_length: {}, upper_length: {}, conditional_lower_length: {}, condition: SpecialCasingCondition::{condition} }}),",
            lower.offset, upper.offset, conditional.offset, lower.length, upper.length, conditional.length).unwrap();
    }
    pool.validate()?;
    let mut output = HEADER.to_owned();
    output.push_str("\nstatic CASING_STRINGS: &str = concat!(\n");
    for chunk in pool.text.chars().collect::<Vec<_>>().chunks(32) {
        output.push('"');
        for ch in chunk {
            write!(output, "\\u{{{:X}}}", *ch as u32).unwrap();
        }
        output.push_str("\",\n");
    }
    output.push_str(");\n\n// Sorted by code point; looked up with binary search.\npub static SPECIAL_CASING_MAPPINGS: &[(u32, SpecialCasingMapping)] = &[\n");
    output.push_str(&entries);
    output.push_str("];\n\n");
    for (property, name) in
        [("Cased", "UNICODE_CASED_RANGES"), ("Case_Ignorable", "UNICODE_CASE_IGNORABLE_RANGES")]
    {
        let points =
            source::code_points(&files[format!("Binary_Property/{property}/ranges.js").as_str()])?;
        render_ranges(&mut output, name, &points);
    }
    Ok(output)
}

#[derive(Debug, PartialEq, Eq)]
pub struct Range {
    pub lo: u32,
    pub hi: u32,
    pub stride: u32,
}

pub fn stride_ranges(mut points: &[u32]) -> Vec<Range> {
    let mut ranges = Vec::new();
    while let Some(&lo) = points.first() {
        let stride = points.get(1).map_or(1, |next| next - lo);
        let mut hi = lo;
        let mut count = 1;
        while points.get(count) == Some(&(hi + stride)) {
            hi += stride;
            count += 1;
        }
        ranges.push(Range { lo, hi, stride });
        points = &points[count..];
    }
    ranges
}

fn render_ranges(output: &mut String, name: &str, points: &[u32]) {
    let (bmp, astral) = points.split_at(points.partition_point(|&point| point <= 0xFFFF));
    let r16 = stride_ranges(bmp);
    let r32 = stride_ranges(astral);
    let latin_offset = r16.iter().take_while(|range| range.hi <= 0xFF).count();
    for (width, ranges) in [(16, r16), (32, r32)] {
        writeln!(output, "static {name}_R{width}: &[Range{width}] = &[").unwrap();
        for Range { lo, hi, stride } in ranges {
            writeln!(output, "Range{width} {{ lo: 0x{lo:X}, hi: 0x{hi:X}, stride: {stride} }},")
                .unwrap();
        }
        output.push_str("];\n");
    }
    writeln!(output, "pub static {name}: RangeTable = RangeTable {{ r16: {name}_R16, r32: {name}_R32, latin_offset: {latin_offset} }};\n").unwrap();
}
