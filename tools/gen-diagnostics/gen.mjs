#!/usr/bin/env node
// Generate the Rust diagnostic catalog from the pinned Go declarations.
import { ROOT, read, write, main, args, requireValue, isMain } from "../lib/cli.mjs";
import path from "node:path";
import { constantNames } from "../lib/rust-names.mjs";
const flags = ["reportsUnnecessary", "elidedInCompatibilityPyramid", "reportsDeprecated"];
const rustFlags = ["reports_unnecessary", "elided_in_compatibility_pyramid", "reports_deprecated"];
export const rustQuote = (text) =>
    '"' +
    [...text]
        .map((c) =>
            c === "\\"
                ? "\\\\"
                : c === '"'
                  ? '\\"'
                  : c.codePointAt(0) < 32 || c.codePointAt(0) === 127
                    ? "\\u{" + c.codePointAt(0).toString(16) + "}"
                    : c,
        )
        .join("") +
    '"';
if (isMain(import.meta.url))
    main(() => {
        args("Generate Rust diagnostics from ts-ref/tsc/internal/diagnostics/diagnostics_generated.go.");
        const messages = [],
            order = [];
        let inAll = false;
        const goString = '"(?:[^"\\\\]|\\\\.)*"',
            pattern = new RegExp(
                `^var (\\w+) = &Message\\{code: (\\d+), category: Category(\\w+), key: (${goString}), text: (${goString})((?:, \\w+: true)*)\\}$`,
            );
        const unquote = (value) => {
            requireValue(
                [...value.matchAll(/\\./g)].every((m) => ['\\"', "\\\\"].includes(m[0])),
                `unsupported Go escape in ${value}`,
            );
            return JSON.parse(value);
        };
        for (const line of read(path.join(ROOT, "ts-ref/tsc/internal/diagnostics/diagnostics_generated.go")).split(
            "\n",
        )) {
            if (line.startsWith("var allMessages = ")) {
                inAll = true;
                continue;
            }
            if (inAll) {
                if (line === "}") inAll = false;
                else {
                    const m = line.match(/^\t&(\w+),$/);
                    requireValue(m, `unexpected allMessages line: ${line}`);
                    order.push(m[1]);
                }
                continue;
            }
            if (!line.startsWith("var ")) continue;
            const m = line.match(pattern);
            requireValue(m, `unparsed var line: ${line}`);
            const [, name, code, category, key, text, fields] = m,
                present = [...fields.matchAll(/, (\w+): true/g)].map((m) => m[1]);
            requireValue(
                ["Warning", "Error", "Suggestion", "Message"].includes(category),
                `unknown category ${category}`,
            );
            for (const f of present) requireValue(flags.includes(f), `unknown flag ${f}`);
            requireValue(
                !new Set(
                    "as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try gen".split(
                        " ",
                    ),
                ).has(name),
                "identifier is a Rust keyword: " + name,
            );
            messages.push({ name, code, category, key: unquote(key), text: unquote(text), present });
        }
        requireValue(
            JSON.stringify(messages.map((m) => m.name)) === JSON.stringify(order),
            "allMessages order does not match var declarations",
        );
        requireValue(new Set(order).size === order.length, "duplicate identifiers");
        const rustNames = constantNames(order);
        const out = [
            "// Code generated by tools/gen-diagnostics/gen.mjs from diagnostics_generated.go; DO NOT EDIT.",
            "",
            "use crate::{Category, Key, Message};",
            "",
        ];
        for (const m of messages)
            out.push(
                `pub static ${rustNames.get(m.name)}: Message = Message { code: ${m.code}, category: Category::${m.category}, key: Key(${rustQuote(m.key)}), text: ${rustQuote(m.text)}, ${flags.map((f, i) => `${rustFlags[i]}: ${m.present.includes(f)}`).join(", ")} };`,
                "",
            );
        out.push(
            `pub static ALL_MESSAGES: [&Message; ${messages.length}] = [`,
            ...order.map((n) => `    &${rustNames.get(n)},`),
            "];",
            "",
        );
        write(path.join(ROOT, "crates/tsrs_diagnostics/src/generated.rs"), out.join("\n"));
        console.log(`wrote ${messages.length} messages to crates/tsrs_diagnostics/src/generated.rs`);
    });
