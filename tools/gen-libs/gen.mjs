#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { ROOT, read, write, args, main, requireValue } from "../lib/cli.mjs";
main(() => {
    args("Copy pinned bundled libraries and generate the Rust library registry.");
    const source = path.join(ROOT, "ts-ref/tsc/internal/bundled"),
        crate = path.join(ROOT, "crates/tsrs_vfs"),
        copyright = read(path.join(source, "CopyrightNotice.txt"));
    requireValue(
        !copyright.includes("\r") && copyright.endsWith("\n\n"),
        "CopyrightNotice.txt must use LF line endings and end with a blank line",
    );
    const libs = fs.readdirSync(path.join(source, "libs")).sort();
    for (const name of libs) {
        const file = path.join(source, "libs", name);
        requireValue(
            fs.statSync(file).isFile() && name.startsWith("lib.") && name.endsWith(".d.ts"),
            `unexpected entry in libs: ${name}`,
        );
        const content = read(file);
        requireValue(
            !content.includes("\r") && content.startsWith(copyright + "\n") && content.endsWith("\n"),
            `${file}: invalid copyright or line endings`,
        );
    }
    fs.rmSync(path.join(crate, "libs"), { recursive: true, force: true });
    fs.mkdirSync(path.join(crate, "libs"));
    for (const lib of libs) fs.copyFileSync(path.join(source, "libs", lib), path.join(crate, "libs", lib));
    const header = "// Code generated by tools/gen-libs/gen.mjs; DO NOT EDIT.\n\n";
    write(
        path.join(crate, "src/bundled/libs_generated.rs"),
        header +
            "// LIB_NAMES is the list of all bundled lib files, sorted by name.\n// For the list of libs sorted by load order, use tsoptions::LIBS.\npub static LIB_NAMES: &[&str] = &[\n" +
            libs.map((lib) => `    "${lib}",`).join("\n") +
            "\n];\n",
    );
    write(
        path.join(crate, "src/bundled/embed_generated.rs"),
        header +
            "pub static EMBEDDED_CONTENTS: &[(&str, &str)] = &[\n" +
            libs.map((lib) => `    ("libs/${lib}", include_str!("../../libs/${lib}")),`).join("\n") +
            "\n];\n",
    );
});
