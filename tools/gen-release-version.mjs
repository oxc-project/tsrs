#!/usr/bin/env node
import path from "node:path";
import { ROOT, args, main, read, requireValue, write } from "./lib/cli.mjs";

main(() => {
    const values = args("Generate the TypeScript source pin used by packaged tsrs builds.", { check: false });
    const table = read(path.join(ROOT, "Cargo.toml")).split("[workspace.metadata.typescript]")[1]?.split(/^\[/m)[0];
    const version = table?.match(/^version\s*=\s*"([^"]+)"/m)?.[1];
    const commit = table?.match(/^commit\s*=\s*"([0-9a-f]{40})"/m)?.[1];
    requireValue(version && commit, "Cargo.toml needs a TypeScript version and 40-character source commit");
    const file = path.join(ROOT, "crates/tsrs_execute/src/release_generated.rs");
    const content =
        "// Code generated by tools/gen-release-version.mjs; DO NOT EDIT.\n\n" +
        `const TYPESCRIPT_VERSION: &str = ${JSON.stringify(version)};\n` +
        `const TYPESCRIPT_COMMIT: &str = ${JSON.stringify(commit)};\n`;
    if (values.check) {
        requireValue(read(file) === content, "Run node tools/gen-release-version.mjs after updating the TypeScript pin");
    } else write(file, content);
});
