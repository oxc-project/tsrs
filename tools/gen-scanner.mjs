// Generate the concrete legacy scanner before Rust lowers its methods as generics.
// The owned implementation is the single algorithm source during the migration.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const root = 'crates/tsrs_scanner/src/';
const write = (name, source) => {
  const path = root + name;
  source = execFileSync('rustfmt', ['--edition', '2024', '--config-path', '.rustfmt.toml', '--emit', 'stdout'], {
    input: source,
    encoding: 'utf8',
  });
  if (!fs.existsSync(path) || fs.readFileSync(path, 'utf8') !== source) fs.writeFileSync(path, source);
};
const header = '// Code generated by tools/gen-scanner.mjs. DO NOT EDIT.\n\n';
// Only text ownership operations are erased. A new clone/conversion elsewhere
// in the algorithm must retain its meaning in the concrete implementation.
const specialize = source => {
  for (const text of ['self.state.token_value', 'self.scanner.state.token_value', 'cached_value', 'cached', 'original', 'token_value', 'digits']) {
    source = source.replaceAll(`${text}.clone()`, text);
  }
  for (const text of ['self.state.token_value', 'token_value', 'reference.name', 'digits', 'v']) {
    source = source.replaceAll(`${text}.as_ref()`, text);
  }
  for (const text of ['raw_text', 'digits', 'original']) {
    source = source.replaceAll(`${text}.into()`, text);
  }
  return source
  .replaceAll("ScannerImpl<'src, S>", 'Scanner')
  .replaceAll("ScannerStateImpl<S::Text>", 'ScannerState')
  .replaceAll("SavedScannerStateImpl<S::Text>", 'SavedScannerState')
  .replaceAll('S::Text', "&'static str")
  .replaceAll('S::Builder', 'ArenaStringBuilder')
  .replaceAll('S::copy_text', 'alloc_str')
  .replaceAll("'src", "'static")
  .replaceAll('.finish()', '.into_str()')
  .replaceAll(/\((&self\.text(?:\(\))?\[[^\n]+?\])\)\.into\(\)/g, '$1')
  .replaceAll(/(self\.slice\([^\n;]*?\))\.into\(\)/g, '$1')
  .replaceAll(/("(?:[^"\\]|\\.)*")\.into\(\)/g, '$1')
  .replace('return if start == end { "" } else { self.slice(start, end) }.into();', 'return if start == end { "" } else { self.slice(start, end) };');
};

const input = fs.readFileSync(root + 'scanner_impl.rs', 'utf8');
const marker = "impl<'src, S: ScannerText<'src>> ScannerImpl<'src, S> {";
const start = input.indexOf(marker);
if (start < 0) throw new Error('Missing scanner implementation');
let scanner = input.slice(start).replace(marker, 'impl Scanner {');
const dispatchStart = scanner.indexOf('    const BYTE_HANDLERS:');
const dispatchEnd = scanner.indexOf('\n    fn default_scanner()', dispatchStart);
if (dispatchStart < 0 || dispatchEnd < 0) throw new Error('Missing scanner dispatch');
// Keep the original concrete static's compilation boundary. Check its complete
// initializer so a change to shared dispatch cannot silently leave it behind.
const concreteDispatch = scanner.slice(dispatchStart, dispatchEnd)
  .replace('const BYTE_HANDLERS: [fn(&mut Self) -> Option<Kind>; 256]', 'static BYTE_HANDLERS: [ByteHandler; 256]')
  .replace('as fn(&mut Self) -> Option<Kind>', 'as ByteHandler')
  .replaceAll('Self::', 'Scanner::');
const legacy = fs.readFileSync(root + 'scanner.rs', 'utf8');
const legacyStart = legacy.indexOf('static BYTE_HANDLERS:');
const legacyEnd = legacy.indexOf('\n};', legacyStart) + 3;
if (legacyStart < 0 || legacyEnd < 3 ||
    concreteDispatch.replaceAll(/\s/g, '') !== legacy.slice(legacyStart, legacyEnd).replaceAll(/\s/g, '')) {
  throw new Error('Concrete byte dispatch differs from the shared scanner algorithm');
}
scanner = scanner.slice(0, dispatchStart) + scanner.slice(dispatchEnd);
scanner = scanner
  .replace('S::snapshot(&self.state)', 'self.state')
  .replace('S::pin_unless_source(self.text, key, value);', `let in_text = |s: &str| {
            let (p, t) = (s.as_ptr() as usize, self.text.as_ptr() as usize);
            s.is_empty() || (p >= t && p + s.len() <= t + self.text.len())
        };
        if !in_text(key) || !in_text(value) {
            tsrs_core::arena_pin();
        }`)
  .replaceAll('Self::BYTE_HANDLERS', 'BYTE_HANDLERS')
  .replaceAll('Self::default_scanner()', 'Scanner::default_scanner()')
  .replace('fn default_scanner() -> Self', 'fn default_scanner() -> Scanner')
  .replace('pub fn new() -> Self', 'pub fn new() -> Scanner')
  .replace('Self { skip_trivia:', 'Scanner { skip_trivia:')
  .replaceAll('ScannerStateImpl::default()', 'ScannerState::default()')
  .replace('        SavedScannerStateImpl {', '        SavedScannerState {')
  .replaceAll(/if let Some\((cached(?:_value)?)\)/g, 'if let Some(&$1)');
scanner = specialize(scanner)
  .replace('impl Scanner {\n\n', 'impl Scanner {\n')
  .replace('truncate(self.state.comment_directives_len)', 'truncate(state.comment_directives_len)')
  .replaceAll('&self.state.token_value', 'self.state.token_value')
  .replaceAll('self.concat_value(self.state.token_value, &parts)', 'self.concat_value(self.state.token_value, parts)')
  .replaceAll('value.push_str(&digits)', 'value.push_str(digits)')
  .replaceAll('s.push_str(&a)', 's.push_str(a)')
  .replaceAll('self.pin_unless_source(&digits,', 'self.pin_unless_source(digits,')
  .replaceAll('self.pin_unless_source(&original, &token_value)', 'self.pin_unless_source(original, token_value)')
  .replaceAll('self.pin_unless_source(original, &digits)', 'self.pin_unless_source(original, digits)')
  .replaceAll('value.push_str(&self.scan_identifier_parts(variant))', 'value.push_str(self.scan_identifier_parts(variant))')
  .replaceAll('parse_int_32(&hex_digits, 16)', 'parse_int_32(hex_digits, 16)')
  .replaceAll('crate::number::parse_literal(&v)', 'crate::number::parse_literal(v)')
  .replaceAll('jsnum::from_string(&v)', 'jsnum::from_string(v)');
write('scanner_legacy_generated.rs', header + scanner);

let regexp = fs.readFileSync(root + 'regexp_impl.rs', 'utf8')
  .replace('use crate::text::ScannerText;\n', '')
  .replace('use super::{', 'use crate::scanner::{')
  .replaceAll("impl<'src, S: ScannerText<'src>>", 'impl')
  .replace("RegExpParser<'src, S: ScannerText<'src>>", 'RegExpParser')
  .replaceAll("RegExpParser<'src, S>", 'RegExpParser')
  .replace('RUNE_ERROR, ScannerImpl, decode_rune', 'RUNE_ERROR, Scanner, decode_rune')
  .replace('struct GroupNameReference<T>', 'struct GroupNameReference')
  .replace('    name: T,', "    name: &'static str,")
  .replace('fn add_unique<T: PartialEq>(set: &mut Vec<T>, name: T)', "fn add_unique(set: &mut Vec<&'static str>, name: &'static str)");
regexp = specialize(regexp)
  .replaceAll("GroupNameReference<&'static str>", 'GroupNameReference')
  .replaceAll('group.iter().any(|entry| entry.as_ref() == name)', 'group.contains(&name)')
  .replaceAll('compare_decimal_strings(&min_str, &max_str)', 'compare_decimal_strings(min_str, max_str)')
  .replaceAll('self.named_capturing_groups_contains(&self.scanner.state.token_value)', 'self.named_capturing_groups_contains(self.scanner.state.token_value)')
  .replaceAll('self.group_specifiers_order.iter().map(AsRef::as_ref)', 'self.group_specifiers_order.iter().copied()')
  .replace(') -> Self {', ') -> RegExpParser {');
write('regexp.rs', header + regexp);
