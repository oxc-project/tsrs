// Generates the per-node-struct field tables of the AST oracle from the AST schema, so that the Go dumper
// (tools/oracle/ast/fields_gen.go, read via reflection) and the Rust dumper
// (crates/tsrs_parser/examples/ast_oracle/fields.rs) print the same non-child fields in the same order:
// node lists (loc + length, modifier flags), raw lists, and scalars (bool, string, int, TokenFlags, Kind).
//
// Usage: node tools/oracle/ast/gen-fields.ts

import * as fs from "node:fs";
import * as path from "node:path";
import { api } from "../../gen-ast/schema.ts";

const root = path.resolve(import.meta.dirname, "../../..");

const RUST_KEYWORDS = new Set(["type", "in", "as", "ref", "mod", "match", "loop", "override", "static", "const", "struct", "enum", "impl", "fn", "let", "yield", "abstract", "final", "use", "where", "true", "false", "self", "super", "crate", "move", "return", "if", "else", "for", "while", "break", "continue", "pub", "trait", "unsafe", "extern", "dyn", "async", "await", "box", "do", "macro", "priv", "typeof", "unsized", "virtual", "try"]);

function snake(s: string): string {
    s = s.replace(/JSDoc/g, "Jsdoc");
    return s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2").toLowerCase();
}

function ident(s: string): string {
    const n = snake(s);
    return RUST_KEYWORDS.has(n) ? n + "_" : n;
}

type Cat = "list" | "modlist" | "rawnodes" | "rawstrings" | "bool" | "string" | "int" | "tokenflags" | "kind";

function category(m: any): Cat | undefined {
    if (m.noGo || m.goOnly || m.isKindParam()) return undefined;
    const t = m.type;
    const bk = t.baseKind();
    if (bk === "node") return undefined;
    if (t.kind === "list" || bk === "list") {
        const lk = m.listKind;
        if (lk === "ModifierList") return "modlist";
        if (lk === "raw") {
            return t.elementType.baseKind() === "node" ? "rawnodes" : "rawstrings";
        }
        return "list";
    }
    if (bk === "kind") return "kind";
    if (bk === "primitive") {
        switch (t.name) {
            case "bool":
                return "bool";
            case "string":
                return "string";
            case "int":
                return "int";
            case "TokenFlags":
                return "tokenflags";
            case "NodeFlags":
            case "any":
                return undefined;
        }
    }
    throw new Error(`unhandled member ${m.name}`);
}

const go: string[] = [];
const rs: string[] = [];
go.push("// Code generated by tools/oracle/ast/gen-fields.ts. DO NOT EDIT.");
go.push("");
go.push("package main");
go.push("");
go.push('import "reflect"');
go.push('import "github.com/microsoft/TypeScript/tsc/internal/ast"');
go.push("");
go.push("var nodeFields = map[string][]fieldSpec{");
rs.push("// Code generated by tools/oracle/ast/gen-fields.ts. DO NOT EDIT.");
rs.push("");
rs.push("use tsrs_ast::{Node, NodeData};");
rs.push("");
rs.push("use crate::Dumper;");
rs.push("");
rs.push("pub fn dump_fields(n: &Node, d: &mut Dumper) {");
rs.push("    match n.data() {");
for (const n of api.nodes()) {
    const fields: [string, Cat][] = [];
    for (const m of n.members) {
        const c = category(m);
        if (c) fields.push([m.name, c]);
    }
    if (fields.length === 0) continue;
    go.push(`\t${JSON.stringify(n.name)}: {${fields.map(([f, c]) => `{${JSON.stringify(f)}, ${JSON.stringify(c)}}`).join(", ")}},`);
    rs.push(`        NodeData::${n.name}(x) => {`);
    for (const [f, c] of fields) {
        rs.push(`            d.field_${c}(${JSON.stringify(f)}, x.${ident(f)}());`);
    }
    rs.push("        }");
}
go.push("}");
go.push("");
go.push("// Concrete nodes embed Node; recover their data through the generated checked casts.");
go.push("func nodeData(n *ast.Node) reflect.Value {");
go.push("    switch n.Kind {");
const canonicalNodes = new Map<string, ReturnType<typeof api.nodes>[number]>();
for (const node of api.nodes()) for (const kind of node.allKinds()) canonicalNodes.set(kind.name, node);
const canonicalKinds = new Map<ReturnType<typeof api.nodes>[number], string[]>();
for (const [kind, node] of canonicalNodes) {
    const kinds = canonicalKinds.get(node) ?? [];
    kinds.push(kind);
    canonicalKinds.set(node, kinds);
}
for (const [node, kinds] of canonicalKinds) {
    if (!node.members.some(member => category(member) !== undefined)) continue;
    go.push(`    case ${kinds.map(kind => `ast.Kind${kind}`).join(", ")}: return reflect.ValueOf(n.As${node.name}()).Elem()`);
}
go.push("    default: return reflect.Value{}");
go.push("    }");
go.push("}");
rs.push("        _ => {}");
rs.push("    }");
rs.push("}");
fs.writeFileSync(path.join(root, "tools/oracle/ast/fields_gen.go"), go.join("\n") + "\n");
fs.writeFileSync(path.join(root, "crates/tsrs_parser/examples/ast_oracle/fields.rs"), rs.join("\n") + "\n");
