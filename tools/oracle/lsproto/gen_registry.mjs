#!/usr/bin/env node
import path from "node:path";
import { ROOT, args, read, write, main } from "../../lib/cli.mjs";
main(() => {
    args("Generate Go and Rust LSP oracle type registries.");
    const go = read(path.join(ROOT, "ts-ref/tsc/internal/lsp/lsproto/lsp_generated.go")),
        special = ["Message", "RequestMessage", "ResponseMessage"],
        names = [...go.matchAll(/^type (\w+) (struct \{|struct\{\}|int32$|uint32$|string$)/gm)]
            .map((m) => m[1])
            .filter((n) => !n.startsWith("Resolved") && n !== "RegisterOptions")
            .concat(special);
    write(
        path.join(ROOT, "tools/oracle/lsproto/registry_gen.go"),
        '// Code generated by gen_registry.mjs; DO NOT EDIT.\n\npackage main\n\nimport "github.com/microsoft/TypeScript/tsc/internal/lsp/lsproto"\n\nvar registryNames = []string{\n' +
            names
                .filter((n) => !special.includes(n))
                .map((n) => `\t"${n}",\n`)
                .join("") +
            "}\n\nvar registry = map[string]func() any{\n" +
            names.map((n) => `\t"${n}": func() any { return new(lsproto.${n}) },\n`).join("") +
            "}\n",
    );
    write(
        path.join(ROOT, "crates/tsrs_lsproto/tests/oracle_registry/mod.rs"),
        "// Code generated by tools/oracle/lsproto/gen_registry.mjs; DO NOT EDIT.\n\nuse tsrs_lsproto::*;\n\npub fn roundtrip(name: &str, data: &[u8]) -> Option<String> {\n    Some(match name {\n" +
            names.map((n) => `        "${n}" => run::<${n}>(data),\n`).join("") +
            '        _ => return None,\n    })\n}\n\nfn run<T: Json>(data: &[u8]) -> String {\n    match unmarshal::<T>(data) {\n        Ok(v) => match marshal(&v) {\n            Ok(s) => format!("OK {s}"),\n            Err(e) => format!("MERR {e}"),\n        },\n        Err(e) => format!("ERR {}", e.to_string().replace(\'\\n\', "\\\\n")),\n    }\n}\n',
    );
    console.log(names.length, "types");
});
