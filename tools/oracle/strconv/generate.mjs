// Regenerate with Go 1.27 (Unicode 17): node tools/oracle/strconv/generate.mjs
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../../../", import.meta.url);
const goRoot = execFileSync("go", ["env", "GOROOT"], {
    cwd: new URL("ts-ref/tsc/", root),
    env: { ...process.env, GOTOOLCHAIN: "auto", GOWORK: "off" },
    encoding: "utf8",
}).trim();
const unicode = readFileSync(join(goRoot, "src/unicode/tables.go"), "utf8");
assert.match(unicode, /const Version = "17\.0\.0"/);
const source = readFileSync(join(goRoot, "src/strconv/isprint.go"), "utf8");
let output = "// Code generated by tools/oracle/strconv/generate.mjs (Go Unicode 17.0.0). DO NOT EDIT.\n"
    + "// Copyright 2013 The Go Authors. All rights reserved.\n"
    + "// Use of this source code is governed by the BSD-style license in licenses/Go-LICENSE.\n\n";
for (const [goName, rustName, type] of [
    ["isPrint16", "IS_PRINT16", "u16"],
    ["isNotPrint16", "IS_NOT_PRINT16", "u16"],
    ["isPrint32", "IS_PRINT32", "u32"],
    ["isNotPrint32", "IS_NOT_PRINT32", "u16"],
]) {
    const table = source.match(new RegExp(`var ${goName} = \\[\\]uint\\d+\\{([\\s\\S]*?)\\n\\}`));
    assert.ok(table, `missing Go table ${goName}`);
    const literals = table[1].replace(/\/\/[^\n]*/g, "").match(/0x[0-9a-f]+/g);
    assert.ok(literals?.length);
    const values = literals.map(value => {
        const hex = Number(value).toString(16).padStart(type === "u32" ? 8 : 4, "0");
        return "0x" + (type === "u32" ? hex.slice(0, 4) + "_" + hex.slice(4) : hex);
    });
    output += `#[rustfmt::skip]\npub(super) static ${rustName}: &[${type}] = &[\n`;
    for (let i = 0; i < values.length; i += 8) {
        output += `    ${values.slice(i, i + 8).join(", ")},\n`;
    }
    output += "];\n\n";
}
const directory = new URL("crates/tsrs_core/src/gocompat/", root);
mkdirSync(directory, { recursive: true });
writeFileSync(new URL("isprint_generated.rs", directory), output);
