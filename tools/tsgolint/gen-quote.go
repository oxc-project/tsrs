// Generates the printable rune ranges used for Go diagnostic string quoting.
package main

import (
	"fmt"
	"strconv"
)

func main() {
	fmt.Println("//! Go `strconv.IsPrint` ranges, generated by `go run tools/tsgolint/gen-quote.go` with Go 1.27.1.")
	fmt.Println("\npub(super) const PRINTABLE: &[(u32, u32)] = &[")
	for r := rune(0); r <= 0x10ffff; r++ {
		if !strconv.IsPrint(r) {
			continue
		}
		start := r
		for r < 0x10ffff && strconv.IsPrint(r+1) {
			r++
		}
		fmt.Printf("    (0x%x, 0x%x),\n", start, r)
	}
	fmt.Println("];")
}
