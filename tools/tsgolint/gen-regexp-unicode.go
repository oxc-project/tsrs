package main

import (
	"fmt"
	"unicode"
)

func flags(r rune) uint8 {
	var mask uint8
	if unicode.In(r, unicode.L, unicode.Mn, unicode.Nd, unicode.Pc) || r == '\u200c' || r == '\u200d' {
		mask |= 1
	}
	start := r == '$' || r == '_' || unicode.In(r, unicode.L, unicode.Nl, unicode.Other_ID_Start)
	if start {
		mask |= 2
	}
	if start || r == '\u200c' || r == '\u200d' || unicode.In(r, unicode.Mn, unicode.Mc, unicode.Nd, unicode.Pc, unicode.Other_ID_Continue) {
		mask |= 4
	}
	return mask
}

func main() {
	if unicode.Version != "17.0.0" {
		panic("regexp2 compatibility requires Unicode 17.0.0")
	}
	fmt.Println("//! regexp2 Unicode 17 predicates, generated by `go run tools/tsgolint/gen-regexp-unicode.go`.")
	fmt.Print(`
fn has_flag(ch: char, flag: u8) -> bool {
    let code = ch as u32;
    let index = RANGES.partition_point(|&(_, end, _)| end < code);
    RANGES.get(index).is_some_and(|&(start, _, flags)| start <= code && flags & flag != 0)
}

pub(super) fn is_word_char(ch: char) -> bool { has_flag(ch, 1) }
pub(super) fn is_identifier_start(ch: char) -> bool { has_flag(ch, 2) }
pub(super) fn is_identifier_part(ch: char) -> bool { has_flag(ch, 4) }

const RANGES: &[(u32, u32, u8)] = &[
`)
	for r := rune(0); r <= 0x10ffff; r++ {
		mask := flags(r)
		if mask == 0 {
			continue
		}
		start := r
		for r < 0x10ffff && flags(r+1) == mask {
			r++
		}
		fmt.Printf("    (0x%x, 0x%x, %d),\n", start, r, mask)
	}
	fmt.Println("];")
}
